import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'feedback.dart';
import 'firebase_options.dart'; // This file was generated by flutterfire configure
import 'screens/home_screen.dart';
import 'theme.dart';

void main() async {
  // 1. Ensure Flutter bindings are initialized before Firebase
  WidgetsFlutterBinding.ensureInitialized();

  // Keep recent errors so feedback reports arrive with them
  DebugLog.install();

  // 2. Initialize Firebase using the generated options
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  runApp(const ToddlerActivityApp());
}

/// Widest the app gets; wider windows (desktop browsers) show it centered.
const double _maxContentWidth = 600;

class ToddlerActivityApp extends StatelessWidget {
  const ToddlerActivityApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'ToddleGo',
      debugShowCheckedModeBanner: false,
      theme: buildAppTheme(),
      // On wide screens (the web version) keep the phone layout: a centered
      // column, as wide as a large phone, on a light background
      builder: (context, child) => ColoredBox(
        color: AppColors.surfaceMuted,
        child: Center(
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: _maxContentWidth),
            child: child,
          ),
        ),
      ),
      home: const HomeScreen(),
    );
  }
}
